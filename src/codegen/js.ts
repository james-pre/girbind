/**
 * ESM entry-point emitter.
 *
 * Imports the other bound namespaces this one can see, so their classes are
 * registered with the runtime first, then loads the compiled addon and calls its
 * `$init` with the runtime ABI. The addon defines every class natively (with
 * parents from other namespaces looked up in the runtime) and returns them, and
 * the entry point re-exports them under the same names.
 *
 * Built from generator functions that `yield` lines; {@link generate} joins
 * them. Emitted code is tab-indented.
 */

import type { Enumeration, Namespace } from '../ir.js';
import { functionExportNames, propertyKey } from '../names.js';
import type { Repository } from '../parse.js';
import { TypeContext } from '../types.js';
import { boundClasses } from './cxx.js';

type Lines = Generator<string, void, void>;

/**
 * Emit an enum as a runtime object, mirroring how TypeScript compiles a numeric
 * enum: a bi-directional map with both `name -> value` and `value -> "name"`
 * entries so reverse lookups work.
 */
function* enumDecl(e: Enumeration): Lines {
	yield `export const ${e.name} = {`;
	for (const m of e.members) {
		yield `\t${propertyKey(m.name)}: ${m.value},`;
		yield `\t${propertyKey(m.value)}: '${m.name}',`;
	}
	yield '};\n';
}

export interface Options {
	/** Require path to the built `.node`, relative to the entry point. */
	addonPath: string;
	repository?: Repository;
	/** Import specifiers of other bound namespaces, by namespace name. */
	modules?: Record<string, string>;
}

function* file(ns: Namespace, options: Options): Lines {
	const ctx = new TypeContext(ns, options.repository, options.modules);
	const classNames = boundClasses(ctx).map(cls => cls.name);
	const functionNames = functionExportNames(ns).map(f => f.jsName);

	yield `// Generated by girbind from ${ns.name}-${ns.version}`;
	yield '// DO NOT EDIT THIS FILE DIRECTLY';
	yield '';
	yield "import { createRequire } from 'node:module';";
	yield "import { internal } from 'girbind';";
	for (const name of ctx.importedNamespaces()) yield `import '${ctx.modules[name]}';`;
	yield '';
	yield `const addon = createRequire(import.meta.url)('${options.addonPath}').$init(internal);`;
	yield '';

	if (classNames.length || functionNames.length) {
		yield 'export const {';
		for (const name of [...classNames, ...functionNames]) yield `\t${name},`;
		yield '} = addon;\n';
	}

	for (const e of ns.enumerations) yield* enumDecl(e);

	yield 'export default {';
	for (const name of [...classNames, ...functionNames, ...ns.enumerations.map(e => e.name)]) {
		yield `\t${name},`;
	}
	yield '};';
}

export function generate(ns: Namespace, options: Options): string {
	return [...file(ns, options)].join('\n') + '\n';
}
